// Compiles the contracts with solc 0.8.28 (solc-js, no download) into artifacts/: ABI and bytecode for each.
//   node build.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const solc = require("solc");

export const SETTINGS = { optimizer: { enabled: true, runs: 200 }, evmVersion: "shanghai", viaIR: false };
const sources = {
  "src/NomadAgents.sol": { content: readFileSync(join(here, "src/NomadAgents.sol"), "utf8") },
  "test/src/TestToken.sol": { content: readFileSync(join(here, "test/src/TestToken.sol"), "utf8") }
};
const findImports = (p) => {
  try {
    return { contents: readFileSync(require.resolve(p), "utf8") };
  } catch {
    return { error: `Not found: ${p}` };
  }
};
const input = { language: "Solidity", sources, settings: { ...SETTINGS, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } } } };
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
mkdirSync(join(here, "artifacts"), { recursive: true });
// The exact compiler input for NomadAgents alone, to verify the deployed contract on the explorer (Blockscout:
// "Solidity (Standard JSON input)", compiler v0.8.28).
{
  const used = {};
  const add = (p) => {
    if (used[p]) return;
    const content = p.startsWith("src/") ? sources[p].content : readFileSync(require.resolve(p), "utf8");
    used[p] = { content };
    const dir = p.slice(0, p.lastIndexOf("/") + 1);
    for (const m of content.matchAll(/^import\s+(?:\{[^}]*\}\s+from\s+)?"([^"]+)";/gm)) {
      const target = m[1].startsWith(".") ? new URL(m[1], `file:///${dir}`).pathname.slice(1) : m[1];
      add(target);
    }
  };
  add("src/NomadAgents.sol");
  writeFileSync(join(here, "artifacts", "NomadAgents.standard-input.json"), JSON.stringify({ language: "Solidity", sources: used, settings: { ...SETTINGS, outputSelection: { "*": { "*": ["abi", "evm.bytecode", "evm.deployedBytecode", "metadata"] } } } }, null, 2) + "\n");
}
for (const [file, name] of [["src/NomadAgents.sol", "NomadAgents"], ["test/src/TestToken.sol", "TestToken"]]) {
  const c = out.contracts[file][name];
  writeFileSync(join(here, "artifacts", `${name}.json`), JSON.stringify({ contractName: name, compiler: solc.version(), settings: SETTINGS, abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` }, null, 2) + "\n");
  console.log(`${name}: ${c.evm.deployedBytecode.object.length / 2} bytes deployed`);
}

// The site's copy of the ABI and the deployment bytecode (apps/web reads these; a test checks they match).
{
  const a = JSON.parse(readFileSync(join(here, "artifacts", "NomadAgents.json"), "utf8"));
  const web = join(here, "..", "apps", "web", "lib");
  writeFileSync(join(web, "agents-contract.ts"), `// Generated by contracts/build.mjs from contracts/src/NomadAgents.sol. Do not edit.\nexport const AGENTS_ABI = ${JSON.stringify(a.abi, null, 2)} as const;\n`);
  writeFileSync(join(web, "agents-bytecode.ts"), `// Generated by contracts/build.mjs from contracts/src/NomadAgents.sol (solc ${a.compiler}). Do not edit.\nexport const AGENTS_BYTECODE = "${a.bytecode}" as const;\n`);
}
